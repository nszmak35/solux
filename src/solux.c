void
commitnotify(struct wl_listener *listener, void *data)
{
	Client *c = wl_container_of(listener, c, commit);

	if (c->surface.xdg->initial_commit) {
		/*
		 * Capture the actual visible Float canvas before the initial
		 * applyrules()/setmon() sequence.  setmon() focuses the top client,
		 * and with animations disabled that focus changes canvas_x/canvas_y
		 * immediately.  Spawn geometry must not depend on that focus.
		 */
		nfloat_capture_spawn_canvas(c);

		applyrules(c);
		if (c->mon) {
			client_set_scale(client_surface(c), c->mon->wlr_output->scale);
		}
		setmon(c, NULL, 0); /* Make sure to reapply rules in mapnotify() */

		wlr_xdg_toplevel_set_wm_capabilities(c->surface.xdg->toplevel,
				WLR_XDG_TOPLEVEL_WM_CAPABILITIES_FULLSCREEN);
		if (c->decoration)
			requestdecorationmode(&c->set_decoration_mode, c->decoration);
		wlr_xdg_toplevel_set_size(c->surface.xdg->toplevel, 0, 0);
		return;
	}

	resize(c, c->geom, (c->isfloating && !c->isfullscreen));

	/*
	 * A SceneFX buffer does not necessarily exist yet when mapnotify() runs.
	 * Applying opacity/effects there can therefore miss the first real buffer.
	 * Commit is the first reliable point at which the mapped surface and its
	 * scene buffers are available.  Do the same per-client runtime application
	 * here that reload_config() performs, without changing layout or rules.
	 */
	if (client_surface(c)->mapped && c->scene && c->scene_surface) {
		Client *focused = c->mon ? focustop(c->mon) : NULL;

		c->corner_radius = scenefx_corner_radius;
		update_client_rounded_borders(c);

		if (scenefx_shadow && !c->shadow) {
			c->shadow = wlr_scene_shadow_create(c->scene, 0, 0,
				c->corner_radius, scenefx_shadow_blur_sigma,
				scenefx_shadow_color);
			if (c->shadow)
				wlr_scene_node_lower_to_bottom(&c->shadow->node);
		}
		if (c->shadow)
			update_client_shadow_color(c);

		if (scenefx_blur && !c->blur) {
			c->blur = wlr_scene_blur_create(c->scene, 0, 0);
			if (c->blur)
				wlr_scene_node_place_below(&c->blur->node,
					&c->scene_surface->node);
		}
		if (c->blur) {
			wlr_scene_node_set_enabled(&c->blur->node, scenefx_blur);
			update_client_blur(c);
		}

		c->opacity = (c == focused)
			? scenefx_opacity_active : scenefx_opacity_inactive;
		wlr_scene_node_for_each_buffer(&c->scene_surface->node,
			iter_xdg_scene_buffers, c);

		if (c->mon && c->mon->blur_layer && scenefx_blur) {
			wlr_scene_optimized_blur_set_size(c->mon->blur_layer,
				c->mon->m.width, c->mon->m.height);
			wlr_scene_optimized_blur_mark_dirty(c->mon->blur_layer);
		}
	}

	/* mark a pending resize as completed */
	if (c->resize && c->resize <= c->surface.xdg->current.configure_serial)
		c->resize = 0;
}

void
commitpopup(struct wl_listener *listener, void *data)
{
	struct wlr_surface *surface = data;
	struct wlr_xdg_popup *popup = wlr_xdg_popup_try_from_wlr_surface(surface);
	LayerSurface *l = NULL;
	Client *c = NULL;
	struct wlr_box box;
	int type = -1;

	if (!popup->base->initial_commit)
		return;

	type = toplevel_from_wlr_surface(popup->base->surface, &c, &l);
	if (!popup->parent || type < 0)
		return;
	popup->base->surface->data = wlr_scene_xdg_surface_create(
			popup->parent->data, popup->base);
	if ((l && !l->mon) || (c && !c->mon)) {
		wlr_xdg_popup_destroy(popup);
		return;
	}
	box = type == LayerShell ? l->mon->m : c->mon->w;
	box.x -= (type == LayerShell ? l->scene->node.x : c->geom.x);
	box.y -= (type == LayerShell ? l->scene->node.y : c->geom.y);
	wlr_xdg_popup_unconstrain_from_box(popup, &box);
	wl_list_remove(&listener->link);
	free(listener);
}

