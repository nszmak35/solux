void
spawn(const Arg *arg)
{
	const char *command = arg ? (const char *)arg->v : NULL;

	if (!command || !*command)
		return;

	if (fork() == 0) {
		close(STDIN_FILENO);
		dup2(STDERR_FILENO, STDOUT_FILENO);
		setsid();
		execl("/bin/sh", "sh", "-c", command, (char *)NULL);
		dprintf(STDERR_FILENO, "solux: /bin/sh -c %s: %s\n", command, strerror(errno));
		_exit(127);
	}
}


void
tag(const Arg *arg)
{
	Client *sel = focustop(selmon);
	uint32_t newtags;
	if (!sel || (arg->ui & TAGMASK) == 0)
		return;

	newtags = arg->ui & TAGMASK;
	if (sel->mon == selmon && solux_canvas_active(selmon) && sel->isfloating)
		solux_canvas_record_client_geom(sel);
	/* A window moved exclusively to a tag with a real layout must become a
	 * tiled client.  Floating state belongs to the current window placement;
	 * leaving it set here makes a window arrive on a dwindle/tile/monocle tag
	 * with its old Float geometry and bypass the layout. */
	sel->tags = newtags;
	solux_apply_tag_layout(sel, selmon, newtags);
	/* A client moved to another tag is no longer visible on this workspace.
	 * Unlike a normal view switch, this path does not create a tag transition,
	 * so make sure its old scene node cannot remain as a visual ghost. */
	if (!VISIBLEON(sel, selmon)) {
		sel->animation.running = false;
		wlr_scene_node_set_enabled(&sel->scene->node, false);
		client_set_suspended(sel, true);
	}
	focusclient(focustop(selmon), 1);
	arrange(selmon);
}

